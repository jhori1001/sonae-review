// Refreshes price and Rakuten review count/average for the products already
// in lib/real-products.generated.ts, without changing which products are
// listed. (Re-running import-rakuten.mjs instead would rebuild the list from
// search results, and any product that dropped out would take its reviews
// on this site with it.) Run weekly by .github/workflows/refresh-prices.yml;
// locally: `node refresh-rakuten-prices.mjs` with the keys in .env.local.
import fs from 'node:fs';

const FILE = 'lib/real-products.generated.ts';
const env = {...process.env};
if (fs.existsSync('.env.local')) {
  for (const line of fs.readFileSync('.env.local', 'utf8').split('\n')) {
    const i = line.indexOf('=');
    if (i < 1) continue;
    const key = line.slice(0, i);
    let val = line.slice(i + 1);
    if (val.startsWith('"') && val.endsWith('"')) val = val.slice(1, -1);
    env[key] ??= val;
  }
}
for (const key of ['RAKUTEN_APP_ID', 'RAKUTEN_ACCESS_KEY', 'RAKUTEN_AFFILIATE_ID']) {
  if (!env[key]) { console.error(`Missing ${key}`); process.exit(1); }
}

const source = fs.readFileSync(FILE, 'utf8');
const start = source.indexOf('= [') + 2;
const products = JSON.parse(source.slice(start, source.lastIndexOf(']') + 1));
const header = source.slice(0, start).replace(/^\/\/ (Prices refreshed|AUTO-GENERATED).*\n/gm, '');

const slugify = itemCode => 'rk-' + itemCode.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

async function lookup(itemCode) {
  const url = new URL('https://openapi.rakuten.co.jp/ichibams/api/IchibaItem/Search/20260701');
  url.searchParams.set('applicationId', env.RAKUTEN_APP_ID);
  url.searchParams.set('accessKey', env.RAKUTEN_ACCESS_KEY);
  url.searchParams.set('affiliateId', env.RAKUTEN_AFFILIATE_ID);
  url.searchParams.set('itemCode', itemCode);
  url.searchParams.set('format', 'json');
  url.searchParams.set('formatVersion', '2');
  const res = await fetch(url, {headers: {referer: 'https://sonae-review.vercel.app/', origin: 'https://sonae-review.vercel.app'}});
  if (!res.ok) throw new Error(`${res.status} ${(await res.text()).slice(0, 200)}`);
  return (await res.json()).Items?.[0];
}

let updated = 0, unchanged = 0;
const missing = [];
for (const p of products) {
  // Ids are slugified "shop:item" codes. Shop codes may contain hyphens, so
  // the item part is taken as everything after the last hyphen and the
  // result is checked against the id before it is trusted.
  const body = p.id.slice(3);
  const cut = body.lastIndexOf('-');
  const itemCode = `${body.slice(0, cut)}:${body.slice(cut + 1)}`;
  try {
    const item = await lookup(itemCode);
    if (!item || slugify(item.itemCode) !== p.id) { missing.push(p.id); continue; }
    const next = {price: item.itemPrice, rakutenReviewCount: item.reviewCount || 0, rakutenReviewAverage: item.reviewAverage || 0};
    if (Object.entries(next).some(([k, v]) => p[k] !== v)) { Object.assign(p, next); updated++; } else unchanged++;
  } catch (error) {
    console.error(`  ${p.id}: ${error.message}`);
    missing.push(p.id);
  }
  await new Promise(r => setTimeout(r, 1100)); // Rakuten allows about 1 request per second
}

console.log(`updated ${updated}, unchanged ${unchanged}, not found ${missing.length}`);
if (missing.length) console.log('Not found (kept as is — may be sold out or delisted):', missing.join(', '));
if (missing.length > products.length / 2) { console.error('More than half not found; leaving the file untouched.'); process.exit(1); }
const stamp = `// AUTO-GENERATED by import-rakuten.mjs.\n// Prices refreshed by refresh-rakuten-prices.mjs on ${new Date().toISOString().slice(0, 10)}.\n`;
fs.writeFileSync(FILE, stamp + header + JSON.stringify(products, null, 1) + ';\n', 'utf8');
